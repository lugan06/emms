CREATE TABLE IF NOT EXISTS `cms_category` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键，Java 对应 Long',
    `parent_id` BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '父栏目 ID，0 表示顶级栏目',
    `name` VARCHAR(100) NOT NULL COMMENT '栏目名称',
    `code` VARCHAR(100) NOT NULL COMMENT '栏目编码，全局唯一',
    `url_name` VARCHAR(150) NULL COMMENT '公共端 URL 名称',
    `model_code` VARCHAR(50) NOT NULL DEFAULT 'ARTICLE' COMMENT '内容模型：PAGE、ARTICLE、PRODUCT、CASE、LINK、DIRECTORY',
    `list_template` VARCHAR(100) NULL COMMENT '列表页模板编码',
    `detail_template` VARCHAR(100) NULL COMMENT '详情页模板编码',
    `sort_order` INT NOT NULL DEFAULT 0 COMMENT '栏目排序值，数值越小越靠前',
    `is_enabled` TINYINT NOT NULL DEFAULT 1 COMMENT '是否启用：0 否，1 是',
    `show_in_nav` TINYINT NOT NULL DEFAULT 1 COMMENT '是否显示在公共端导航：0 否，1 是',
    `link_url` VARCHAR(500) NULL COMMENT 'LINK 类型栏目跳转地址',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 未删除，1 已删除',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_cms_category_code` (`code`),
    KEY `idx_cms_category_parent_sort` (`parent_id`, `sort_order`),
    KEY `idx_cms_category_enabled_nav` (`is_enabled`, `show_in_nav`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='内容栏目表';

CREATE TABLE IF NOT EXISTS `cms_content` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键，Java 对应 Long',
    `category_id` BIGINT UNSIGNED NOT NULL COMMENT '所属栏目 ID，关联 cms_category.id',
    `exhibition_id` BIGINT UNSIGNED NULL COMMENT '所属展会 ID，关联 exhibition.id',
    `title` VARCHAR(200) NOT NULL COMMENT '内容标题',
    `slug` VARCHAR(150) NULL COMMENT '公共端 URL 标识',
    `cover_url` VARCHAR(500) NULL COMMENT '内容封面图地址',
    `summary` TEXT NULL COMMENT '内容摘要',
    `body` LONGTEXT NULL COMMENT '正文内容，支持富文本',
    `author` VARCHAR(100) NULL COMMENT '作者',
    `source` VARCHAR(200) NULL COMMENT '内容来源',
    `status` VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT '内容状态：DRAFT、PUBLISHED、OFFLINE',
    `published_at` DATETIME NULL COMMENT '发布时间',
    `sort_order` INT NOT NULL DEFAULT 0 COMMENT '内容排序值，数值越小越靠前',
    `is_top` TINYINT NOT NULL DEFAULT 0 COMMENT '是否置顶：0 否，1 是',
    `is_recommend` TINYINT NOT NULL DEFAULT 0 COMMENT '是否推荐：0 否，1 是',
    `view_count` INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '浏览次数',
    `extra_data` JSON NULL COMMENT '扩展属性 JSON',
    `created_by` BIGINT UNSIGNED NULL COMMENT '创建人，关联 admin_user.id',
    `updated_by` BIGINT UNSIGNED NULL COMMENT '最后修改人，关联 admin_user.id',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 未删除，1 已删除',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_cms_content_slug` (`slug`),
    KEY `idx_cms_content_category_status_publish` (`category_id`, `status`, `published_at`),
    KEY `idx_cms_content_exhibition_status_publish` (`exhibition_id`, `status`, `published_at`),
    KEY `idx_cms_content_recommend_sort` (`is_recommend`, `is_top`, `sort_order`),
    KEY `idx_cms_content_created_by` (`created_by`),
    CONSTRAINT `fk_cms_content_category` FOREIGN KEY (`category_id`) REFERENCES `cms_category` (`id`) ON DELETE RESTRICT ON UPDATE RESTRICT,
    CONSTRAINT `fk_cms_content_exhibition` FOREIGN KEY (`exhibition_id`) REFERENCES `exhibition` (`id`) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT `fk_cms_content_created_by` FOREIGN KEY (`created_by`) REFERENCES `admin_user` (`id`) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT `fk_cms_content_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `admin_user` (`id`) ON DELETE SET NULL ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='栏目内容表';

CREATE TABLE IF NOT EXISTS `file_asset` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键，Java 对应 Long',
    `original_name` VARCHAR(255) NOT NULL COMMENT '原始文件名',
    `storage_name` VARCHAR(255) NOT NULL COMMENT '存储文件名',
    `file_url` VARCHAR(500) NOT NULL COMMENT '文件访问地址',
    `file_type` VARCHAR(100) NOT NULL COMMENT '文件 MIME 类型或扩展名',
    `file_size` BIGINT UNSIGNED NOT NULL COMMENT '文件大小，单位字节',
    `file_hash` VARCHAR(100) NULL COMMENT '文件哈希，可用于去重',
    `uploaded_by` BIGINT UNSIGNED NULL COMMENT '上传人，关联 admin_user.id',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 未删除，1 已删除',
    PRIMARY KEY (`id`),
    KEY `idx_file_asset_hash` (`file_hash`),
    KEY `idx_file_asset_type_created` (`file_type`, `created_at`),
    KEY `idx_file_asset_uploaded_by` (`uploaded_by`),
    CONSTRAINT `fk_file_asset_uploaded_by` FOREIGN KEY (`uploaded_by`) REFERENCES `admin_user` (`id`) ON DELETE SET NULL ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='文件资源表';

CREATE TABLE IF NOT EXISTS `guestbook` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键，Java 对应 Long',
    `name` VARCHAR(100) NOT NULL COMMENT '留言人姓名',
    `phone` VARCHAR(30) NULL COMMENT '联系电话',
    `email` VARCHAR(150) NULL COMMENT '联系邮箱',
    `company_name` VARCHAR(200) NULL COMMENT '公司名称',
    `message` TEXT NOT NULL COMMENT '留言内容',
    `status` VARCHAR(20) NOT NULL DEFAULT 'UNREAD' COMMENT '留言状态：UNREAD、READ、REPLIED、CLOSED',
    `reply_content` TEXT NULL COMMENT '管理员回复内容',
    `replied_by` BIGINT UNSIGNED NULL COMMENT '回复人，关联 admin_user.id',
    `replied_at` DATETIME NULL COMMENT '回复时间',
    `ip_address` VARCHAR(64) NULL COMMENT '提交 IP 地址',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 未删除，1 已删除',
    PRIMARY KEY (`id`),
    KEY `idx_guestbook_status_created_at` (`status`, `created_at`),
    KEY `idx_guestbook_phone` (`phone`),
    KEY `idx_guestbook_replied_by` (`replied_by`),
    CONSTRAINT `fk_guestbook_replied_by` FOREIGN KEY (`replied_by`) REFERENCES `admin_user` (`id`) ON DELETE SET NULL ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='在线留言表';

CREATE TABLE IF NOT EXISTS `operation_log` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键，Java 对应 Long',
    `admin_user_id` BIGINT UNSIGNED NULL COMMENT '操作人 ID，关联 admin_user.id',
    `username` VARCHAR(50) NULL COMMENT '操作账号快照',
    `module` VARCHAR(50) NOT NULL COMMENT '业务模块',
    `operation` VARCHAR(100) NOT NULL COMMENT '操作名称',
    `request_method` VARCHAR(10) NULL COMMENT 'HTTP 请求方法',
    `request_url` VARCHAR(500) NULL COMMENT '请求地址',
    `request_ip` VARCHAR(64) NULL COMMENT '请求 IP 地址',
    `request_params` JSON NULL COMMENT '请求参数，敏感字段必须脱敏',
    `result` VARCHAR(20) NOT NULL DEFAULT 'SUCCESS' COMMENT '操作结果：SUCCESS、FAILURE',
    `error_message` VARCHAR(500) NULL COMMENT '失败原因',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 未删除，1 已删除',
    PRIMARY KEY (`id`),
    KEY `idx_operation_log_user_created` (`admin_user_id`, `created_at`),
    KEY `idx_operation_log_module_operation` (`module`, `operation`),
    KEY `idx_operation_log_result_created` (`result`, `created_at`),
    CONSTRAINT `fk_operation_log_admin_user` FOREIGN KEY (`admin_user_id`) REFERENCES `admin_user` (`id`) ON DELETE SET NULL ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='操作日志表';
