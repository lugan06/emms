
-- EEMS 第一版数据库建表脚本
-- MySQL 8.x / InnoDB / utf8mb4
-- 本文件仅包含建表语句，不包含初始化数据和执行命令。

CREATE TABLE IF NOT EXISTS `admin_user` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键，Java 对应 Long',
    `username` VARCHAR(50) NOT NULL COMMENT '登录账号',
    `password_hash` VARCHAR(255) NOT NULL COMMENT 'BCrypt 密码哈希，不保存明文密码',
    `nickname` VARCHAR(100) NOT NULL COMMENT '管理员显示名称',
    `avatar_url` VARCHAR(500) NULL COMMENT '头像地址',
    `role_code` VARCHAR(50) NOT NULL COMMENT '角色编码：SUPER_ADMIN、EDITOR',
    `status` VARCHAR(20) NOT NULL DEFAULT 'ENABLED' COMMENT '账号状态：ENABLED、DISABLED',
    `last_login_at` DATETIME NULL COMMENT '最近登录时间',
    `last_login_ip` VARCHAR(64) NULL COMMENT '最近登录 IP 地址',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 未删除，1 已删除',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_admin_user_username` (`username`),
    KEY `idx_admin_user_role_status` (`role_code`, `status`),
    KEY `idx_admin_user_created_at` (`created_at`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='管理员账号表';

CREATE TABLE IF NOT EXISTS `exhibition` (
    `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '主键，Java 对应 Long',
    `exhibition_code` VARCHAR(100) NOT NULL COMMENT '展会业务编码',
    `title` VARCHAR(200) NOT NULL COMMENT '展会标题',
    `subtitle` VARCHAR(200) NULL COMMENT '展会副标题',
    `year` SMALLINT NOT NULL COMMENT '举办年份',
    `edition` VARCHAR(50) NULL COMMENT '届次，例如第二十一届',
    `cover_url` VARCHAR(500) NULL COMMENT '展会封面图地址',
    `summary` TEXT NULL COMMENT '展会简介',
    `description` LONGTEXT NULL COMMENT '展会详细描述，支持富文本',
    `venue` VARCHAR(200) NULL COMMENT '展馆或举办地点',
    `address` VARCHAR(500) NULL COMMENT '详细地址',
    `start_at` DATETIME NOT NULL COMMENT '展会开始时间',
    `end_at` DATETIME NOT NULL COMMENT '展会结束时间',
    `status` VARCHAR(20) NOT NULL DEFAULT 'DRAFT' COMMENT '展会状态：DRAFT、PUBLISHED、OFFLINE',
    `show_on_home` TINYINT NOT NULL DEFAULT 0 COMMENT '是否显示在首页：0 否，1 是',
    `home_sort` INT NOT NULL DEFAULT 0 COMMENT '首页排序值，数值越小越靠前',
    `published_at` DATETIME NULL COMMENT '发布时间',
    `contact_name` VARCHAR(100) NULL COMMENT '展会联系人',
    `contact_phone` VARCHAR(30) NULL COMMENT '展会联系电话',
    `registration_url` VARCHAR(500) NULL COMMENT '报名地址',
    `extra_data` JSON NULL COMMENT '扩展属性 JSON',
    `created_by` BIGINT UNSIGNED NULL COMMENT '创建人，关联 admin_user.id',
    `updated_by` BIGINT UNSIGNED NULL COMMENT '最后修改人，关联 admin_user.id',
    `created_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    `updated_at` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    `deleted` TINYINT NOT NULL DEFAULT 0 COMMENT '逻辑删除：0 未删除，1 已删除',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_exhibition_code` (`exhibition_code`),
    KEY `idx_exhibition_status_start_at` (`status`, `start_at`),
    KEY `idx_exhibition_home_sort` (`show_on_home`, `home_sort`),
    KEY `idx_exhibition_year` (`year`),
    KEY `idx_exhibition_created_by` (`created_by`),
    CONSTRAINT `fk_exhibition_created_by` FOREIGN KEY (`created_by`) REFERENCES `admin_user` (`id`) ON DELETE SET NULL ON UPDATE RESTRICT,
    CONSTRAINT `fk_exhibition_updated_by` FOREIGN KEY (`updated_by`) REFERENCES `admin_user` (`id`) ON DELETE SET NULL ON UPDATE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='展会信息表';

