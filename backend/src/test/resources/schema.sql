CREATE TABLE IF NOT EXISTS site (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    code VARCHAR(50) NOT NULL UNIQUE,
    status VARCHAR(20) NOT NULL DEFAULT 'DISABLED',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT chk_site_status CHECK (status IN ('ENABLED', 'DISABLED'))
);
CREATE INDEX IF NOT EXISTS idx_site_status_created ON site(status, created_at);
CREATE TABLE IF NOT EXISTS site_domain (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    site_id BIGINT NOT NULL,
    domain VARCHAR(253) NOT NULL UNIQUE,
    is_primary TINYINT NOT NULL DEFAULT 0,
    -- H2 uses the same expression without MySQL's STORED keyword.
    primary_site_id BIGINT GENERATED ALWAYS AS (CASE WHEN is_primary = 1 THEN site_id ELSE NULL END),
    CONSTRAINT uk_site_domain_primary_site UNIQUE (primary_site_id),
    CONSTRAINT chk_site_domain_is_primary CHECK (is_primary IN (0, 1)),
    FOREIGN KEY (site_id) REFERENCES site(id)
);
MERGE INTO site (id, name, code, status) KEY (id) VALUES (1, 'Default site', 'default', 'ENABLED');
MERGE INTO site_domain (id, site_id, domain, is_primary) KEY (id) VALUES (1, 1, 'localhost', 0);
MERGE INTO site_domain (id, site_id, domain, is_primary) KEY (id) VALUES (2, 1, '127.0.0.1', 0);

CREATE TABLE IF NOT EXISTS admin_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(100) NOT NULL,
    avatar_url VARCHAR(500),
    role_code VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ENABLED',
    auth_version BIGINT NOT NULL DEFAULT 0,
    last_login_at TIMESTAMP,
    last_login_ip VARCHAR(64),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0,
    CONSTRAINT chk_admin_user_auth_version CHECK (auth_version >= 0)
);

CREATE TABLE IF NOT EXISTS admin_user_site (
    admin_user_id BIGINT NOT NULL,
    site_id BIGINT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (admin_user_id, site_id),
    CONSTRAINT fk_admin_user_site_admin FOREIGN KEY (admin_user_id) REFERENCES admin_user(id),
    CONSTRAINT fk_admin_user_site_site FOREIGN KEY (site_id) REFERENCES site(id)
);
CREATE INDEX IF NOT EXISTS idx_admin_user_site_site ON admin_user_site(site_id, admin_user_id);

CREATE TABLE IF NOT EXISTS operation_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    site_id BIGINT,
    admin_user_id BIGINT,
    username VARCHAR(50),
    module VARCHAR(50),
    operation VARCHAR(100),
    request_method VARCHAR(10),
    request_url VARCHAR(500),
    request_ip VARCHAR(64),
    request_params TEXT,
    result VARCHAR(20),
    error_message TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    deleted TINYINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS site_config (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 100000) PRIMARY KEY,
    site_id BIGINT NOT NULL DEFAULT 1 UNIQUE REFERENCES site(id),
    config_code VARCHAR(100),
    current_exhibition_id BIGINT,
    hero_video_url VARCHAR(500),
    site_title VARCHAR(200),
    site_subtitle VARCHAR(200),
    domain VARCHAR(255),
    logo_url VARCHAR(500),
    keywords VARCHAR(500),
    description TEXT,
    icp_number VARCHAR(100),
    template_code VARCHAR(100),
    statistics_code TEXT,
    footer_info TEXT,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    deleted INT DEFAULT 0
);
